"""Known fixture state: dataset + trained versions + a fresh registry with v1 bootstrapped as champion."""

from __future__ import annotations

import json
import time
from pathlib import Path
from typing import Any

from .data import build_dataset
from .paths import MANIFEST_DIR, StatePaths
from .policy import ReleasePolicy
from .runtime import Runtime, build_runtime, register_all
from .train import load_config, main_train_all, model_configs

CHAMPION_BOOTSTRAP = "v1-logreg"


class FixtureError(RuntimeError):
    pass


def build_data(paths: StatePaths, check_committed: bool = True) -> dict[str, Any]:
    manifest = build_dataset(paths.data)
    committed = MANIFEST_DIR / "dataset_manifest.json"
    if check_committed and committed.exists():
        old = json.loads(committed.read_text())
        if old["dataset_hash"] != manifest["dataset_hash"]:
            raise FixtureError(
                f"regenerated dataset hash {manifest['dataset_hash'][:16]} != committed "
                f"{old['dataset_hash'][:16]} (generator or numpy changed); rerun with --update-manifests"
            )
    (paths.data / "dataset_manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True))
    return manifest


def write_committed_manifests(dataset_manifest: dict[str, Any], model_manifests: list[dict[str, Any]]) -> None:
    MANIFEST_DIR.mkdir(exist_ok=True)
    (MANIFEST_DIR / "dataset_manifest.json").write_text(json.dumps(dataset_manifest, indent=2, sort_keys=True) + "\n")
    out = MANIFEST_DIR / "models"
    out.mkdir(exist_ok=True)
    for m in model_manifests:
        t = m["metrics"]["test"]
        summary = {
            "contract": m["contract"],
            "version": m["version"],
            "family": m["family"],
            "config_sha256": m["training"]["config_sha256"],
            "dataset_hash": m["dataset"]["dataset_hash"],
            "test_prediction_sha256": m["test_prediction_sha256"],
            "threshold": m["threshold"],
            "deliberately_degraded": m["deliberately_degraded"],
            "data_change": m["training"]["data_change"],
            "test_metrics": {
                k: t[k]
                for k in (
                    "n",
                    "positives",
                    "pr_auc",
                    "pr_auc_ci95",
                    "roc_auc",
                    "precision",
                    "recall",
                    "f1",
                    "brier",
                    "ece",
                )
            },
            "note": "Committed summary; the artifact itself is regenerated by "
            "`make train-fixtures` (var/ is gitignored).",
        }
        (out / f"{m['version']}.json").write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n")


def train_fixtures(paths: StatePaths, update_manifests: bool = False, log: Any = print) -> dict[str, Any]:
    ds = build_data(paths, check_committed=not update_manifests)
    pending = []
    existing = []
    for cfg_path in model_configs():
        cfg = load_config(cfg_path)
        mf = paths.artifacts / cfg["version"] / "manifest.json"
        if mf.exists():
            m = json.loads(mf.read_text())
            if m["training"]["config_sha256"] != cfg["_sha256"] or m["dataset"]["dataset_hash"] != ds["dataset_hash"]:
                raise FixtureError(
                    f"{cfg['version']} exists but was trained from a different config/dataset; "
                    "bump the version (versions are immutable) or delete var/artifacts/"
                    f"{cfg['version']} deliberately"
                )
            existing.append(m)
            log(f"{cfg['version']}: already trained (config + dataset hashes match), skipping")
        else:
            pending.append(cfg_path)
    trained = main_train_all(paths, ds, log=log, only=pending) if pending else []
    manifests = sorted(existing + trained, key=lambda m: m["version"])
    committed = MANIFEST_DIR / "models"
    for m in manifests:
        p = committed / f"{m['version']}.json"
        if p.exists() and not update_manifests:
            old = json.loads(p.read_text())
            if old["test_prediction_sha256"] != m["test_prediction_sha256"]:
                raise FixtureError(
                    f"{m['version']} predictions differ from the committed manifest "
                    "(non-reproducible training?); rerun with --update-manifests to accept"
                )
    if update_manifests or not (MANIFEST_DIR / "dataset_manifest.json").exists():
        write_committed_manifests(ds, manifests)
    return {"dataset": ds, "models": manifests}


def fixture_runtime(run_dir: Path, home: Any = None, policy: ReleasePolicy | None = None, clock: Any = None) -> Runtime:
    run_dir.mkdir(parents=True, exist_ok=True)
    rt = build_runtime(
        home, db_path=run_dir / "registry.sqlite", policy=policy, clock=clock, report_dir=run_dir / "reports"
    )
    rt.store.run_id = run_dir.name
    if not rt.store.list_models():
        register_all(rt)
    if not rt.store.deployment().champion_version:
        rt.controller.bootstrap_champion(CHAMPION_BOOTSTRAP, actor="fixture-bootstrap")
    return rt


def new_run_dir(paths: StatePaths, kind: str) -> Path:
    stamp = time.strftime("%Y%m%d-%H%M%S")
    d = paths.runs / f"{kind}-{stamp}"
    i = 1
    while d.exists():
        i += 1
        d = paths.runs / f"{kind}-{stamp}-{i}"
    d.mkdir(parents=True)
    return d


def point_latest(paths: StatePaths, run_dir: Path) -> None:
    link = paths.runs / "latest"
    if link.is_symlink() or link.exists():
        link.unlink()
    link.symlink_to(run_dir.name)
